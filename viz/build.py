#!/usr/bin/env python3
"""Snapshot the AgentProof evidence files into viz/data.js.

Every file is read with `git show <ref>:<path>`, so the page shows exactly what
is committed, and each source records the commit it came from.
Run from the repo root:  python3 viz/build.py
"""
import json, subprocess, pathlib

SOURCES = {
    # key: (ref, path)
    "envelope01": ("origin/main", "task-002/test-inputs/envelope-01.json"),
    "envelope02": ("origin/main", "task-002/test-inputs/envelope-02.json"),
    "failFixture": ("origin/main", "task-002/expected-outputs/sample-01-fail.json"),
    "ohwowDelivery01": ("origin/jesus/task-004", "task-004/checker-run-2026-11-02/sample-01/ohwow-delivery.json"),
    "ohwowResult01": ("origin/jesus/task-004", "task-004/checker-run-2026-11-02/sample-01/checker-result.json"),
    "ohwowDelivery02": ("origin/jesus/task-004", "task-004/checker-run-2026-11-02/sample-02/ohwow-delivery.json"),
    "ohwowResult02": ("origin/jesus/task-004", "task-004/checker-run-2026-11-02/sample-02/checker-result.json"),
    "blockedDelivery02": ("origin/jesus/task-004", "task-004/checker-run-2026-11-02/sample-02/ohwow-blocked-delivery-max-spend-0.25.json"),
    "blockedResult02": ("origin/jesus/task-004", "task-004/checker-run-2026-11-02/sample-02/checker-result-blocked.json"),
    "marketRef01": ("origin/jesus/task-004", "task-004/checker-run-2026-11-02/sample-01/market-job-ref.dry-run.json"),
    "scenarioC": ("origin/jesus/task-008-scenario-c", "scenario-c-evidence.json"),
}

def git(*a):
    return subprocess.check_output(["git", *a], text=True)

data, sources = {}, {}
for key, (ref, path) in SOURCES.items():
    data[key] = json.loads(git("show", f"{ref}:{path}"))
    sha = git("rev-parse", ref).strip()
    sources[key] = {"ref": ref.replace("origin/", ""), "commit": sha, "path": path}

out = pathlib.Path(__file__).with_name("data.js")
out.write_text(
    "// Generated by viz/build.py from committed evidence. Do not edit by hand.\n"
    "window.AGENTPROOF = " + json.dumps({"data": data, "sources": sources}, indent=1, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"wrote {out} ({len(data)} files)")
